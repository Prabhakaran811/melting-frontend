import { useEffect, useMemo, useState } from "react";
import type { Order } from "../../orders/orderTypes";
import { statusTone } from "../../orders/orderTypes";
import type { Furnace } from "../furnaceDashboardTypes";
import SearchSelect from "../../elementStocks/components/SearchSelect";
import type { SelectOption } from "../../elementStocks/components/SearchSelect";

// The dropdown and drawer styles live in the Element Stock stylesheet (all classes are "es-" prefixed)
import "../../elementStocks/ElementStockManagement.css";

interface Props {
  open: boolean;
  furnace: Furnace | null;
  orders: Order[];
  loading: boolean;
  error: boolean;
  saving: boolean;
  onClose: () => void;
  onSubmit: (orderId: number) => void;
}

export default function StartCycleDrawer({
  open,
  furnace,
  orders,
  loading,
  error,
  saving,
  onClose,
  onSubmit,
}: Props) {
  const [orderId, setOrderId] = useState<number | null>(null);
  const [errorText, setErrorText] = useState("");

  useEffect(() => {
    if (!open) return;
    setOrderId(null);
    setErrorText("");
  }, [open]);

  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  // Orders that are still open (the backend checks eligibility again)
  const openOrders = useMemo(
    () =>
      orders.filter((o) => {
        const tone = statusTone(o.status);
        return tone !== "done" && tone !== "cancelled";
      }),
    [orders]
  );

  const options: SelectOption[] = useMemo(
    () =>
      openOrders.map((o) => ({
        id: o.id,
        label: `${o.order_number} · ${o.aim?.customer?.customer_name ?? "?"} · ${o.aim?.product?.product_name ?? "?"}`,
      })),
    [openOrders]
  );

  const selected = openOrders.find((o) => o.id === orderId) ?? null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (orderId === null) {
      setErrorText("Select an order");
      return;
    }
    onSubmit(orderId);
  };

  return (
    <>
      <div className={`es-overlay ${open ? "is-open" : ""}`} onClick={onClose} />
      <aside className={`es-drawer ${open ? "is-open" : ""}`} aria-hidden={!open}>
        <header className="es-drawer__head">
          <div>
            <h2>Start melt cycle</h2>
            <p>
              {furnace ? `${furnace.furnace_no} · ${furnace.name}` : "Select an order for this furnace."}
            </p>
          </div>
          <button type="button" className="es-icon-btn" onClick={onClose} aria-label="Close">
            ✕
          </button>
        </header>

        <form onSubmit={handleSubmit} className="es-form" noValidate>
          <div className={`es-field ${errorText ? "has-error" : ""}`}>
            <span>Production order</span>
            <SearchSelect
              options={options}
              value={orderId}
              onChange={(id) => {
                setOrderId(id);
                setErrorText("");
              }}
              placeholder="Select order"
              searchPlaceholder="Search order, customer or product..."
              emptyText="No open orders. Create an order first."
              loading={loading}
              loadError={error}
              invalid={Boolean(errorText)}
            />
            {errorText && <small>{errorText}</small>}
          </div>

          {selected && (
            <div className="fd-pick">
              <div><span>Customer</span><strong>{selected.aim?.customer?.customer_name ?? "-"}</strong></div>
              <div><span>Product</span><strong>{selected.aim?.product?.product_name ?? "-"}</strong></div>
              <div><span>Drawing</span><strong>{selected.aim?.drawing_no ?? "-"}</strong></div>
              <div><span>Iron type</span><strong>{selected.aim?.iron_type?.name ?? "-"}</strong></div>
            </div>
          )}

          <p className="fd-pick__note">
            The Heat Number is generated by the server. The cycle starts in the Charging stage.
          </p>

          <footer className="es-form__foot">
            <button type="button" className="es-btn es-btn--ghost" onClick={onClose} disabled={saving}>
              Cancel
            </button>
            <button type="submit" className="es-btn es-btn--primary" disabled={saving}>
              {saving ? "Starting..." : "🔥 Start melt"}
            </button>
          </footer>
        </form>
      </aside>
    </>
  );
}